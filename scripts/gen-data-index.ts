/**
 * Generates src/lib/data/files.generated.ts: a static import of every JSON
 * file in the published record (data/<country>/...).
 *
 * The site reads data through this module instead of the filesystem, so it
 * needs no runtime fs (meant for Cloudflare Workers; not yet tested there).
 * Runs automatically before `dev` and `build`; run by hand with
 *   npm run data:index
 */

import { readdirSync, statSync, writeFileSync, mkdirSync } from 'fs';
import { join, relative } from 'path';

const ROOT = process.cwd();
const DATA = join(ROOT, 'data');
const OUT_DIR = join(ROOT, 'src', 'lib', 'data');
const OUT = join(OUT_DIR, 'files.generated.ts');

function walk(dir: string): string[] {
    return readdirSync(dir)
        .sort()
        .flatMap(name => {
            if (name.startsWith('_') || name.startsWith('.')) return []; // _overlays, _merged: unreviewed
            const p = join(dir, name);
            if (statSync(p).isDirectory()) return walk(p);
            return name.endsWith('.json') ? [p] : [];
        });
}

const countries = readdirSync(DATA).filter(d => statSync(join(DATA, d)).isDirectory()).sort();
const files = countries.flatMap(c => walk(join(DATA, c)));

const toPosix = (p: string) => p.replace(/\\/g, '/');
const lines = [
    '// GENERATED by scripts/gen-data-index.ts from data/. Do not edit; run `npm run data:index`.',
    '/* eslint-disable */',
    ...files.map((f, i) => `import f${i} from '${toPosix(relative(OUT_DIR, f))}';`),
    '',
    '/** Every published JSON file, keyed by its path under data/ (e.g. "in/config.json"). */',
    'export const dataFiles: Record<string, unknown> = {',
    ...files.map((f, i) => `    '${toPosix(relative(DATA, f))}': f${i},`),
    '};',
    '',
];

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`[data:index] ${files.length} files from ${countries.length} countr${countries.length === 1 ? 'y' : 'ies'} -> ${toPosix(relative(ROOT, OUT))}`);
